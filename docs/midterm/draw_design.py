OUT = Path(__file__).resolve().parent / 'images'
OUT.mkdir(exist_ok=True)
INK, BLUE, PALE, LINE = '#243448', '#195a94', '#edf4fa', '#bccbd9'
class Canvas:
    def __init__(self, w=1000, h=600):
        self.w, self.h = w, h
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">', '<rect width="100%" height="100%" fill="white"/>', '<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0,0 L8,4 L0,8" fill="#607d98"/></marker></defs>']
    def rect(self,x,y,w,h,fill=PALE):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="7" fill="{fill}" stroke="{LINE}"/>')
    def text(self,x,y,s,size=22,color=INK):
        self.parts.append(f'<text x="{x}" y="{y}" font-family="Microsoft YaHei, Noto Sans SC, sans-serif" font-size="{size}" fill="{color}">{escape(s)}</text>')
    def box(self,x,y,w,h,title,lines=()):
        self.rect(x,y,w,h)
        self.text(x+16,y+32,title,24,BLUE)
        for i,line in enumerate(lines): self.text(x+16,y+65+i*29,line,20)
    def arrow(self,x1,y1,x2,y2):
        self.parts.append(f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="#607d98" stroke-width="2" marker-end="url(#arrow)"/>')
    def save(self,name):
        path=OUT/name
        path.write_text('\n'.join(self.parts+['</svg>']),encoding='utf-8')
        print(path.name)
    def frame(self,title,hint):
        self.rect(8,8,984,self.h-16,'#ffffff')
        self.rect(8,8,984,62,BLUE)
        self.text(28,48,title,25,'white')
        self.text(28,104,hint,20)
        self.text(28,self.h-24,'界面原型 · 示例数据',18,'#66788a')

